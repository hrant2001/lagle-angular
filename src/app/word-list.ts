export async function getValidWords(): Promise<string[]> {
  if (typeof window !== 'undefined' && (window as any)['__WORDS_CACHE']) {
    return (window as any)['__WORDS_CACHE'];
  }

  const RAW_URL = 'https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt';

  const resp = await fetch(RAW_URL);
  if (!resp.ok) throw new Error('Failed to fetch words list');
  const text = await resp.text();
  const words = text
    .split(/\r?\n/)
    .filter((w) => w && w.length === 5)
    .map((w) => w.toLowerCase());

  try {
    const NAMES_URL = 'https://raw.githubusercontent.com/dominictarr/random-name/master/first-names.txt';
    const namesResp = await fetch(NAMES_URL);
    if (namesResp.ok) {
      const namesText = await namesResp.text();
      const namesSet = new Set(
        namesText
          .split(/\r?\n/)
          .filter(Boolean)
          .map((n) => n.toLowerCase())
      );
      const filtered = words.filter((w) => !namesSet.has(w));
      if (typeof window !== 'undefined') (window as any)['__WORDS_CACHE'] = filtered;
      return filtered;
    }
  } catch (e: any) {
    console.warn('Failed to fetch names list for filtering:', e.message || e);
  }

  if (typeof window !== 'undefined') (window as any)['__WORDS_CACHE'] = words;
  return words;
}
